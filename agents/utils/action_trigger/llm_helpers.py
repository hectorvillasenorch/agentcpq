def _normalize_value_block(v):
    if not isinstance(v, dict):
        return None

    t = v.get("type")

    # Detect expression automatically if missing type but formula exists
    if not t and "formula" in v:
        t = "expression"

    out = {"type": t}

    if t == "field":
        out["object"] = v.get("object")
        out["path"] = v.get("path")
    elif t == "static":
        out["data"] = v.get("data")
    elif t == "expression":
        out["formula"] = v.get("formula")
    elif t == "date":
        out["formula"] = v.get("formula")

    return out


def normalize_conditions(cond):
    if not cond:
        return None
    items = []
    for c in cond.get("items", []):
        items.append({
            "alias": c.get("alias"),
            "left": {
                "object": c.get("left", {}).get("object"),
                "path": c.get("left", {}).get("path")
            },
            "operator": c.get("operator"),
            "right": _normalize_value_block(c.get("right"))
        })
    return {"logic": cond.get("logic", "AND"), "items": items}


def normalize_create_value_fields(fields, schema):
    """
    ✅ For CREATE.value.fields: sanitize each entry WITHOUT changing format.
    - If type == field: ensure object/path exist; sanitize path (__c) using resolve_path_from_root(object).
    - If type == static/expression: keep respective property.
    """
    if not isinstance(fields, dict):
        return {}
    out = {}
    for fname, spec in fields.items():
        if not isinstance(spec, dict):
            continue
        t = spec.get("type")
        # Keep original key
        if t == "field":
            obj = spec.get("object")
            path = spec.get("path")
            if isinstance(obj, str) and isinstance(path, str):
                # Resolve path against the declared object (not the event root)
                norm_path = resolve_path_from_root(schema, obj, path)
            else:
                obj = spec.get("object")
                norm_path = _fix_double_c(spec.get("path"))
            out[fname] = {
                "type": "field",
                "object": obj,
                "path": norm_path
            }
        elif t == "static":
            out[fname] = {"type": "static", "data": spec.get("data")}
        elif t == "expression":
            out[fname] = {"type": "expression", "formula": spec.get("formula")}
        elif t == "date":
            out[fname] = {"type": "date", "formula": spec.get("formula")}
        else:
            # Unknown: drop to avoid {"type": null}
            continue
    return out

def _normalize_filter_list(filters, target_obj, schema):
    """
    Normaliza filters para CREATE, UPDATE y DELETE.
    - Resuelve rutas con resolve_path_from_root
    - Limpia __c__c
    - Valida tipos permitidos
    - Limpia filtros inválidos
    """

    clean = []

    if not filters:
        return clean

    for f in filters:
        if not isinstance(f, dict):
            continue

        raw_field = f.get("field")
        operator  = f.get("operator")
        raw_value = f.get("value")

        if not raw_field or not operator or not raw_value:
            continue

        # 1️⃣ Normalizar path del campo
        field_path = resolve_path_from_root(schema, target_obj, raw_field)
        field_path = _fix_double_c(field_path)

        # 2️⃣ Normalizar el value
        val = _normalize_value_block(raw_value)
        if not isinstance(val, dict):
            continue

        # ❌ NO SE PERMITEN expression NI date EN FILTERS
        if val.get("type") in ["expression", "date"]:
            continue

        # Si es field → normalizar referencia
        if val.get("type") == "field":
            vobj = val.get("object")
            vpth = resolve_path_from_root(schema, vobj, val.get("path"))
            val["path"] = _fix_double_c(vpth)

        clean.append({
            "field": field_path,
            "operator": operator,
            "value": val
        })

    return clean


def normalize_actions(actions, schema):
    """
    Enhanced normalizer supporting:
    - CREATE (single or bulk via filters)
    - UPDATE (single path update OR bulk via filters, but NOT both)
    - DELETE (with normalized filters)
    """

    out = []

    for a in actions or []:

        op = (a.get("operation") or "").upper()
        tgt = a.get("target", {}) or {}

        # ----------------------------------------------------------------------
        # 🔵 COMMON EXTRACTS
        # ----------------------------------------------------------------------
        target_obj     = tgt.get("object")
        target_path    = tgt.get("path")
        target_filters = tgt.get("filters", [])

        # Guarantee list
        if target_filters is None:
            target_filters = []
        if not isinstance(target_filters, list):
            target_filters = []

        # ----------------------------------------------------------------------
        # 🟩 CREATE (supports filters)
        # ----------------------------------------------------------------------
        if op == "CREATE":

            fields = a.get("value", {}).get("fields", {})
            fields_norm = normalize_create_value_fields(fields, schema)

            # Always path=None for CREATE
            normalized_target = {
                "object": target_obj,
                "path": None
            }

            # Bulk CREATE (filters)
            if target_filters:
                cleaned_filters = _normalize_filter_list(target_filters, target_obj, schema)
                normalized_target["filters"] = cleaned_filters

            out.append({
                "operation": "CREATE",
                "target": normalized_target,
                "value": {"fields": fields_norm}
            })
            continue

        # ----------------------------------------------------------------------
        # 🟧 UPDATE (supports normal update OR bulk via filters)
        # ----------------------------------------------------------------------
        if op == "UPDATE":

            val = a.get("value") or {}

            # CASE A → Bulk UPDATE (filters present)
            if target_filters:

                cleaned_filters = _normalize_filter_list(target_filters, target_obj, schema)

                normalized_target = {
                    "object": target_obj,   # must be event root object
                    "path": None,           # path MUST be null for bulk updates
                    "filters": cleaned_filters
                }

                out.append({
                    "operation": "UPDATE",
                    "target": normalized_target,
                    "value": _normalize_value_block(val)
                })
                continue

            # CASE B → Normal UPDATE (no filters, must have path)
            normalized_target = {
                "object": target_obj,
                "path": _fix_double_c(target_path)
            }

            out.append({
                "operation": "UPDATE",
                "target": normalized_target,
                "value": _normalize_value_block(val)
            })
            continue

        # ----------------------------------------------------------------------
        # 🔴 DELETE (with normalized filters)
        # ----------------------------------------------------------------------
        if op == "DELETE":

            cleaned_filters = _normalize_filter_list(target_filters, target_obj, schema)

            out.append({
                "operation": "DELETE",
                "target": {
                    "object": target_obj,
                    "filters": cleaned_filters
                },
                "value": None
            })
            continue

        # ----------------------------------------------------------------------
        # Unknown op → ignore silently
        # ----------------------------------------------------------------------
        continue

    return out



