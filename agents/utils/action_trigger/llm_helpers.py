def _fix_double_c(path: str):
    if not isinstance(path, str):
        return path
    # Collapse any repeated "__c" at the end (e.g., "__c__c" → "__c")
    return re.sub(r'(__c)+$', '__c', path)


def _variants_for_field_name(raw: str):
    """Return possible variants to match a field in schema."""
    base = raw.rstrip('_')
    variants = [raw]
    if not raw.endswith("__c"):
        variants.append(f"{raw}__c")
    if raw.endswith("__c"):
        variants.append(raw[:-3])  # try without __c
    # also normalized snake
    s = to_snake_case(base)
    if s not in variants:
        variants.append(s)
    if not s.endswith("__c"):
        variants.append(f"{s}__c")
    return list(dict.fromkeys(variants))  # unique, keep order


def _find_field_path(schema, start_model, target_field, max_depth=4):
    """
    DFS over relations to find a path from start_model to any model containing target_field.
    Returns dot path like "rel1.rel2.field".
    """
    if start_model not in schema:
        return None
    target_variants = _variants_for_field_name(target_field)

    # If field already in root:
    for tv in target_variants:
        if tv in schema[start_model]["fields"]:
            return tv  # just the field

    # DFS
    stack = [(start_model, [], 0)]
    visited = set()
    while stack:
        model, rel_path, depth = stack.pop()
        if depth > max_depth:
            continue
        key = (model, tuple(rel_path))
        if key in visited:
            continue
        visited.add(key)

        # Check fields at this model
        for tv in target_variants:
            if tv in schema[model]["fields"]:
                return ".".join(rel_path + [tv])

        # Traverse relations
        for rel_name, next_model in (schema[model]["relations"] or {}).items():
            if next_model in schema:
                stack.append((next_model, rel_path + [rel_name], depth + 1))

    return None


def resolve_path_from_root(schema, root_model, raw_path):
    """
    - If raw_path already has dots, just sanitize __c and return.
    - If raw_path is a single token and not in root, try to discover nested path.
    """
    if not isinstance(raw_path, str) or not raw_path.strip():
        return raw_path

    raw_path = raw_path.strip()
    # If user already provided a dotted path, just sanitize ending
    if "." in raw_path:
        return ".".join(_fix_double_c(p) for p in raw_path.split("."))

    # Single token: check in root model first
    if root_model in schema and raw_path in schema[root_model]["fields"]:
        return raw_path

    # Try to find via relations
    discovered = _find_field_path(schema, root_model, raw_path, max_depth=5)
    if discovered:
        return _fix_double_c(discovered)

    # Try with "__c" explicitly
    if not raw_path.endswith("__c"):
        discovered = _find_field_path(schema, root_model, f"{raw_path}__c", max_depth=5)
        if discovered:
            return _fix_double_c(discovered)

    # Fallback: return sanitized input
    return _fix_double_c(raw_path)


def normalize_event_type(evt, available_models):
    """
    Coerce action to allowed set and validate object_type.
    """
    if not isinstance(evt, dict):
        return None
    obj = evt.get("object_type")
    act = (evt.get("action") or "").lower().strip()
    action_map = {"created": "create", "updated": "update", "deleted": "delete"}
    act = action_map.get(act, act)
    if obj not in available_models:
        return None
    if act not in ["create", "update", "delete"]:
        return None
    return {"object_type": obj, "action": act}


def actions_are_valid(actions):
    """
    VALIDATION RULES (UPDATED WITH BULK FILTERS SUPPORT)

    Supports:
    - CREATE with fields (normal)
    - CREATE with filters (bulk create)
    - UPDATE with path (normal)
    - UPDATE with filters (bulk update)
    - DELETE (unchanged)

    Rules:
    - UPDATE cannot have path AND filters at the same time.
    - CREATE cannot have both fields AND filters at the same time.
    - CREATE must have: either fields OR filters (at least one).
    """

    if not isinstance(actions, list) or not actions:
        return False

    for a in actions:
        if not isinstance(a, dict):
            return False

        op = (a.get("operation") or "").upper()
        target = a.get("target", {})
        value = a.get("value")

        # Must exist
        if not a.get("target"):
            return False

        # ------------------------------
        # CREATE
        # ------------------------------
        if op == "CREATE":
            fields = (value or {}).get("fields")
            filters = target.get("filters")

            # ❌ Cannot have fields + filters simultaneously
            if fields and filters:
                return False

            # ❌ Must have at least one of them
            if not fields and not filters:
                return False

            # If fields exist → must be a dict
            if fields and not isinstance(fields, dict):
                return False

            # target.path must always be None / absent
            if "path" in target and target.get("path") not in (None, ""):
                return False

            # If filters exist → must be list[dict]
            if filters:
                if not isinstance(filters, list):
                    return False
                if not all(isinstance(f, dict) for f in filters):
                    return False

            continue

        # ------------------------------
        # UPDATE
        # ------------------------------
        if op == "UPDATE":
            path = target.get("path")
            filters = target.get("filters")

            # UPDATE must have a value block
            if not value:
                return False

            # ❌ Cannot use path + filters together
            if path and filters:
                return False

            # If path exists → must be string
            if path and not isinstance(path, str):
                return False

            # If filters exist → must be list[dict]
            if filters:
                if not isinstance(filters, list):
                    return False
                if not all(isinstance(f, dict) for f in filters):
                    return False

            # No more constraints
            continue

        # ------------------------------
        # DELETE (unchanged)
        # ------------------------------
        if op == "DELETE":
            filters = target.get("filters")

            if not target.get("object"):
                return False

            if filters:
                if not isinstance(filters, list):
                    return False
                if not all(isinstance(f, dict) for f in filters):
                    return False

            continue

        # Unknown op
        return False

    return True



